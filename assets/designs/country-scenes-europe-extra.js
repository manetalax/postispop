const P=(d,fill='none',stroke='currentColor',w=1.8)=>`<path d="${d}" fill="${fill}" stroke="${stroke}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"/>`;
const R=(x,y,w,h,fill='none',rx=0)=>`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" fill="${fill}" stroke="currentColor" stroke-width="1.6"/>`;
const C=(x,y,r,fill='none')=>`<circle cx="${x}" cy="${y}" r="${r}" fill="${fill}" stroke="currentColor" stroke-width="1.5"/>`;
const E=(x,y,rx,ry,fill='none')=>`<ellipse cx="${x}" cy="${y}" rx="${rx}" ry="${ry}" fill="${fill}" stroke="currentColor" stroke-width="1.5"/>`;
const A=(x,y,w,h,fill='none')=>P(`M${x} ${y+h}V${y+w/2}a${w/2} ${w/2} 0 0 1 ${w} 0v${h-w/2}Z`,fill);
const G=(s,x,y,k=1)=>`<g transform="translate(${x} ${y}) scale(${k})">${s}</g>`;
const windows=(n,x,y,step=13,w=5,h=9)=>Array.from({length:n},(_,i)=>R(x+i*step,y,w,h,'#8a8974')).join('');
const roof=(x,y,w,h=15)=>P(`M${x} ${y}l${w/2}-${h} ${w/2} ${h}Z`,'#b7866d');
const cross=(x,y,s=1)=>P(`M${x} ${y}v${-9*s}m${-3*s} ${4*s}h${6*s}`);
const ground=()=>P('M5 158q68-8 150 0');
const waves=(y=143)=>[0,8,16].map(n=>P(`M5 ${y+n}q20-7 40 0t40 0 40 0`,'none','#84a9a1',1.8)).join('');
const merlons=(x,y,n,step=10)=>P(`M${x} ${y}`+Array.from({length:n},()=>`v-5h${step/2}v5h${step/2}`).join(''));
const house=(x,y,w=28,h=24)=>R(x,y,w,h,'#e0d5b9')+roof(x-2,y,w+4,10)+windows(2,x+5,y+7,w-15,5,8);
